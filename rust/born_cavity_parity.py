import json, math, subprocess, sys
from pathlib import Path

binary = str(Path('target/x86_64-pc-windows-gnu/debug/research-engine.exe').resolve())
sys.path.insert(0, str(Path('..').resolve()))
from domains.fluid_universe.theory import water_born_cavity as bc


def run(*args):
    p = subprocess.run([binary, '--json', 'born-cavity', *map(str, args)],
                       capture_output=True, text=True, encoding='utf-8', timeout=300)
    if p.returncode != 0:
        raise RuntimeError(f'{args}: {p.stderr[:700]}')
    return json.loads(p.stdout)


def close(a, b):
    if isinstance(a, dict):
        return set(a) == set(b) and all(close(a[k], b[k]) for k in a)
    if isinstance(a, list):
        return len(a) == len(b) and all(close(x, y) for x, y in zip(a, b))
    if a is None or b is None:
        return a is b
    if isinstance(a, bool) or isinstance(b, bool):
        return a is b
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        # Golden-section vs scipy bounded minimization (xatol coarse at 1e-10 m).
        return math.isclose(float(a), float(b), rel_tol=1e-3, abs_tol=1e-12)
    return a == b


def check(label, rust, py):
    ok = close(rust, py)
    print(f'{label} equal:', ok)
    if not ok:
        print('  rust:', str(rust)[:800])
        print('  py:  ', str(py)[:800])


for radius in (2.0e-10, 2.86e-10, 4.0e-10):
    check(f'energy {radius}', run('energy', radius), {'value': bc.born_cavity_energy(radius)})
check('equilibrium', run('equilibrium'), bc.born_cavity_equilibrium())
check('scales', run('scales'), bc.born_cavity_scales())
